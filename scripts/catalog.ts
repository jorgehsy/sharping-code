import { readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { parse } from 'yaml';
import { PuzzleCases, PuzzleMeta } from '@sharping/shared';

/** Single source of truth for reading `puzzles/` (used by the generator and by the drift check). */

export const PUZZLES_DIR = join(import.meta.dirname, '..', 'puzzles');
export const CATALOG_FILE = join(import.meta.dirname, '..', 'packages', 'game', 'src', 'catalog.generated.ts');

export const splitFrontmatter = (md: string): { meta: unknown; body: string } => {
  const m = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(md);
  if (!m) throw new Error('puzzle.md: missing YAML frontmatter');
  return { meta: parse(m[1]!), body: md.slice(m[0].length).trim() };
};

/** Renders `packages/game/src/catalog.generated.ts` from `puzzles/*`. Deterministic (sorted by id). */
export async function buildCatalogSource(): Promise<string> {
  const dirs = (await readdir(PUZZLES_DIR, { withFileTypes: true }))
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  const puzzles = [];
  for (const dir of dirs) {
    const { meta, body } = splitFrontmatter(await readFile(join(PUZZLES_DIR, dir, 'puzzle.md'), 'utf8'));
    const parsed = PuzzleMeta.parse(meta);
    if (parsed.id !== dir) throw new Error(`id "${parsed.id}" != folder name "${dir}"`);
    const cases = PuzzleCases.parse(JSON.parse(await readFile(join(PUZZLES_DIR, dir, 'cases.json'), 'utf8')));
    puzzles.push({ ...parsed, statement: body, cases });
  }
  return `// GENERATED by scripts/gen-catalog.ts from puzzles/*. Do not edit; run \`pnpm gen:catalog\`.
// \`pnpm validate:puzzles\` and the game tests fail when this file is stale.
import type { CatalogPuzzle } from './catalog.ts';

export const PUZZLES: readonly CatalogPuzzle[] = ${JSON.stringify(puzzles, null, 2)};
`;
}
